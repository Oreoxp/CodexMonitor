"""
corpus_tool.py — generator + offline verifier for the V2 memory test corpus.

WHY THIS EXISTS
---------------
The ground_truth.yaml of every case carries an `expected_ingest` block whose
`kept_line_nos` / `dropped_line_nos` / `boundary_line_nos` / `raw_event_count`
must match, byte-for-byte, what the Rust S2 ingester + `parse_line` would
classify. Hand-authoring escaped JSON (Chinese, emoji, stringified tool args,
multi-line codex tool-output envelopes) with correct line bookkeeping is
error-prone. So:

  * The rollout-*.jsonl bytes are GENERATED here, from per-case line specs.
  * Every synthesized line is SELF-CHECKED against a faithful Python port of
    backend.rs `parse_line` (the port below mirrors the source verbatim — see
    _anchors/anchors.md §1). A shape mistake fails generation loudly.
  * `expected_ingest` is derived from the generated bytes (truth) and patched
    into each hand-authored ground_truth.yaml (`verify --fix`), so the
    mechanical block is never transcribed by hand.

OWNERSHIP / WORKFLOW
--------------------
  * rollout-*.jsonl   -> GENERATED. Edit the case spec in this file, re-run
                        `gen`. Do not hand-edit the .jsonl.
  * ground_truth.yaml -> HAND-AUTHORED. This tool only ever rewrites the single
                        region between the two `expected_ingest` sentinel
                        comment lines (via `verify --fix`); every semantic block
                        (expected_distill / expected_search / consolidation) is
                        left untouched. Safe to hand-tune per the spec §7 loop.

The S3/S4/S5 *semantic* assertions need a live LLM/embedder and are the
corpus-runner harness's job; this tool verifies only the offline-knowable S2
mechanics + prints the rendered transcript so you can eyeball what the LLM sees.

USAGE
-----
  python3 corpus_tool.py gen                 # (re)write every case's rollout jsonl + print transcripts
  python3 corpus_tool.py verify              # check each yaml's expected_ingest against its jsonl
  python3 corpus_tool.py verify --fix        # rewrite the expected_ingest region from jsonl truth
  python3 corpus_tool.py transcript C012     # dump rendered transcript + segments for one case

stdlib only. No third-party deps (no PyYAML — the yaml region is plain text).
"""

