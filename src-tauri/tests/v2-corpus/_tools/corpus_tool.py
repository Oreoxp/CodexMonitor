def case_jsonl_path(case):
    d = os.path.join(CASES_DIR, case["dirname"])
    return os.path.join(d, "rollout-{}-{}.jsonl".format(case["iso"], case["uuid"]))


def render_lines(case):
    """Return list of (line_no, intended_cls, payload_str) with cosmetic timestamps."""
    out = []
    iso = case["iso"].replace("-", ":", 0)  # keep cosmetic
    # Build a base prefix like 2026-05-10T09:00:00 from the iso (dashes in time -> colons).
    date_part, _, time_part = case["iso"].partition("T")
    time_colon = time_part.replace("-", ":")
    base = "{}T{}".format(date_part, time_colon)
    for i, (cls, payload) in enumerate(case["lines"], start=1):
        ts = "{}.{:03d}Z".format(base, i)
        line_obj = {"timestamp": ts}
        line_obj.update(payload)
        s = json.dumps(line_obj, ensure_ascii=False)
        out.append((i, cls, s))
    return out


def self_check(case, lines):
    problems = []
    for (no, intended, payload_str) in lines:
        actual, _ = parse_line(payload_str)
        if actual != intended:
            problems.append("  L{}: intended={} but parse_line={} :: {}".format(
                no, intended, actual, payload_str[:120]))
    return problems


def compute_ingest(lines):
    kept, dropped, boundary = [], [], []
    for (no, _intended, payload_str) in lines:
        cls, _ = parse_line(payload_str)
        if cls == "kept":
            kept.append(no)
        elif cls == "boundary":
            boundary.append(no)
        else:
            dropped.append(no)
    return {
        "raw_event_count": len(lines),
        "kept_line_nos": kept,
        "dropped_line_nos": dropped,
        "boundary_line_nos": boundary,
    }


def cmd_gen():
    cases = build_cases()
    total = 0
    for case in cases:
        lines = render_lines(case)
        problems = self_check(case, lines)
        if problems:
            print("SELF-CHECK FAILED for {} ({}):".format(case["id"], case["dirname"]))
            print("\n".join(problems))
            sys.exit(1)
        path = case_jsonl_path(case)
        os.makedirs(os.path.dirname(path), exist_ok=True)
        body = "\n".join(s for (_n, _c, s) in lines) + "\n"
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(body)
        ing = compute_ingest(lines)
        segs = segment_thread([(n, s) for (n, _c, s) in lines])
        maxlen = max((len(sg["transcript"]) for sg in segs), default=0)
        total += 1
        print("[gen] {} -> {}".format(case["id"], os.path.relpath(path, CASES_DIR)))
        print("       raw_event_count={} kept={} boundary={} segments={} max_transcript_chars={}".format(
            ing["raw_event_count"], ing["kept_line_nos"], ing["boundary_line_nos"], len(segs), maxlen))
    print("\n[gen] self-check OK for all {} cases. Run `verify --fix` to sync expected_ingest into the yamls.".format(total))


def _fmt_list(xs):
    return "[" + ", ".join(str(x) for x in xs) + "]"


def ingest_block_text(ing):
    return (
        "{start}\n"
        "expected_ingest:\n"
        "  raw_event_count: {n}\n"
        "  kept_line_nos: {kept}\n"
        "  dropped_line_nos: {dropped}\n"
        "  boundary_line_nos: {boundary}\n"
        "{end}"
    ).format(
        start=ING_START, end=ING_END,
        n=ing["raw_event_count"],
        kept=_fmt_list(ing["kept_line_nos"]),
        dropped=_fmt_list(ing["dropped_line_nos"]),
        boundary=_fmt_list(ing["boundary_line_nos"]),
    )


def _parse_int_list(s):
    s = s.strip()
    if s.startswith("[") and s.endswith("]"):
        s = s[1:-1]
    s = s.strip()
    if not s:
        return []
    return [int(x) for x in s.split(",")]


def parse_yaml_ingest_region(text):
    """Extract the expected_ingest values from inside the sentinel region.
    Returns dict or None if region/fields missing."""
    if ING_START not in text or ING_END not in text:
        return None
    region = text.split(ING_START, 1)[1].split(ING_END, 1)[0]
    out = {}
    m = re.search(r"raw_event_count:\s*(\d+)", region)
    if m:
        out["raw_event_count"] = int(m.group(1))
    for key in ("kept_line_nos", "dropped_line_nos", "boundary_line_nos"):
        m = re.search(key + r":\s*(\[[^\]]*\])", region)
        if m:
            out[key] = _parse_int_list(m.group(1))
    needed = {"raw_event_count", "kept_line_nos", "dropped_line_nos", "boundary_line_nos"}
    if not needed.issubset(out.keys()):
        return None
    return out


def cmd_verify(fix=False, only=None):
    cases = build_cases()
    n_pass = n_fail = n_fix = 0
    for case in cases:
        if only and case["id"] != only:
            continue
        lines = render_lines(case)
        problems = self_check(case, lines)
        if problems:
            print("SELF-CHECK FAILED for {}:".format(case["id"]))
            print("\n".join(problems))
            n_fail += 1
            continue
        truth = compute_ingest(lines)
        gt_path = os.path.join(CASES_DIR, case["dirname"], "ground_truth.yaml")
        if not os.path.exists(gt_path):
            print("[verify] {} : ground_truth.yaml MISSING".format(case["id"]))
            n_fail += 1
            continue
        with open(gt_path, "r", encoding="utf-8") as f:
            text = f.read()
        if fix:
            if ING_START in text and ING_END in text:
                before = text.split(ING_START, 1)[0]
                after = text.split(ING_END, 1)[1]
                text = before + ingest_block_text(truth) + after
                with open(gt_path, "w", encoding="utf-8", newline="\n") as f:
                    f.write(text)
                print("[verify --fix] {} : expected_ingest synced".format(case["id"]))
                n_fix += 1
                continue
            else:
                print("[verify --fix] {} : sentinel region MISSING — add the markers first".format(case["id"]))
                n_fail += 1
                continue
        got = parse_yaml_ingest_region(text)
        if got is None:
            print("[verify] {} : expected_ingest region unreadable (run with --fix)".format(case["id"]))
            n_fail += 1
            continue
        ok = (got["raw_event_count"] == truth["raw_event_count"]
              and got["kept_line_nos"] == truth["kept_line_nos"]
              and got["dropped_line_nos"] == truth["dropped_line_nos"]
              and got["boundary_line_nos"] == truth["boundary_line_nos"])
        if ok:
            print("[verify] {} : PASS (raw={}, kept={}, boundary={})".format(
                case["id"], truth["raw_event_count"], truth["kept_line_nos"], truth["boundary_line_nos"]))
            n_pass += 1
        else:
            print("[verify] {} : FAIL".format(case["id"]))
            print("    yaml : {}".format(got))
            print("    truth: {}".format(truth))
            n_fail += 1
    print("\n[verify] pass={} fail={} fixed={}".format(n_pass, n_fail, n_fix))
    if n_fail:
        sys.exit(1)


def cmd_transcript(case_id):
    cases = build_cases()
    for case in cases:
        if case["id"] != case_id:
            continue
        lines = render_lines(case)
        segs = segment_thread([(n, s) for (n, _c, s) in lines])
        print("=== {} {} ===".format(case["id"], case["dirname"]))
        for i, sg in enumerate(segs, start=1):
            print("--- segment {} (lines {}..{}) prior_summary={} ---".format(
                i, sg["start"], sg["end"],
                repr(sg["prior_summary"]) if sg["prior_summary"] is not None else "None"))
            print(sg["transcript"])
            print("[chars={}]".format(len(sg["transcript"])))
        return
    print("no such case: {}".format(case_id))
    sys.exit(1)


def main():
    args = sys.argv[1:]
    if not args:
        print(__doc__)
        sys.exit(0)
    cmd = args[0]
    if cmd == "gen":
        cmd_gen()
    elif cmd == "verify":
        fix = "--fix" in args[1:]
        only = None
        for a in args[1:]:
            if not a.startswith("-"):
                only = a
        cmd_verify(fix=fix, only=only)
    elif cmd == "transcript":
        if len(args) < 2:
            print("usage: corpus_tool.py transcript <CASE_ID>")
            sys.exit(1)
        cmd_transcript(args[1])
    else:
        print("unknown command: {}".format(cmd))
        print(__doc__)
        sys.exit(1)


if __name__ == "__main__":
    main()
