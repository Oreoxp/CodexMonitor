def CALL(name, args_obj, cid="call_x"):
    return ("kept", {"type": "response_item", "payload": {
        "type": "function_call",
        "name": name,
        "arguments": json.dumps(args_obj, ensure_ascii=False),
        "call_id": cid,
    }})


def OUT(output_text, cid="call_x"):
    return ("kept", {"type": "response_item", "payload": {
        "type": "function_call_output",
        "call_id": cid,
        "output": output_text,
    }})


def BOUND(message):
    return ("boundary", {"type": "compacted", "payload": {"message": message}})


def env(output, code=0, tokens=128, chunk="a1b2c3", wall="0.04"):
    """Wrap command output in the real codex exec_command envelope (anchors §5.3)."""
    return (
        "Chunk ID: {chunk}\nWall time: {wall} seconds\n"
        "Process exited with code {code}\nOriginal token count: {tokens}\nOutput:\n{out}"
    ).format(chunk=chunk, wall=wall, code=code, tokens=tokens, out=output)


