# 1. Faithful port of backend.rs parse_line / render_item / segment_thread
#    (anchors.md §1, §2). Returns ('kept'|'boundary'|'dropped', rendered).
#    `rendered` is the transcript line for Kept (or None if render_item
#    would skip it), the summary string for Boundary, None for Dropped.
# =====================================================================

def parse_line(payload: str):
    try:
        v = json.loads(payload)
    except Exception:
        return ("dropped", None)
    if not isinstance(v, dict):
        return ("dropped", None)
    top = v.get("type")
    if not isinstance(top, str):
        return ("dropped", None)
    if top == "compacted":
        p = v.get("payload")
        msg = p.get("message") if isinstance(p, dict) else None
        return ("boundary", msg if isinstance(msg, str) else "")
    if top == "response_item":
        return _parse_response_item(v.get("payload"))
    # session_meta / turn_context / event_msg / unknown
    return ("dropped", None)


def _parse_response_item(p):
    if not isinstance(p, dict):
        return ("dropped", None)
    inner = p.get("type")
    if not isinstance(inner, str):
        return ("dropped", None)
    if inner == "message":
        return _parse_message(p)
    if inner == "function_call":
        return _parse_function_call(p)
    if inner == "function_call_output":
        return _parse_function_call_output(p)
    if inner in (
        "local_shell_call",
        "tool_search_call",
        "tool_search_output",
        "custom_tool_call",
        "custom_tool_call_output",
        "web_search_call",
    ):
        return _parse_tool_misc(p, inner)
    # reasoning / compaction / context_compaction / image_generation_call / unknown
    return ("dropped", None)


def _parse_message(p):
    role = p.get("role")
    if not isinstance(role, str):
        return ("dropped", None)
    if role == "developer":
        return ("dropped", None)
    buf = ""
    content = p.get("content")
    if isinstance(content, list):
        for item in content:
            if not isinstance(item, dict):
                continue
            kind = item.get("type")
            if kind in ("input_text", "output_text"):
                txt = item.get("text")
                if isinstance(txt, str):
                    buf += txt
    if buf.strip() == "":
        return ("dropped", None)
    # render_item Message: skip if whitespace-only (already excluded above)
    return ("kept", "{}: {}".format(role.upper(), buf))


def _parse_function_call(p):
    name = p.get("name")
    args = p.get("arguments")
    name = name if isinstance(name, str) else ""
    args = args if isinstance(args, str) else ""
    if name == "" and args == "":
        return ("dropped", None)
    # render_item ToolCall: None when name AND args are both whitespace-only.
    if name.strip() == "" and args.strip() == "":
        return ("kept", None)
    n = name if name != "" else "<unknown>"
    return ("kept", "TOOL CALL {}: {}".format(n, args))


def _parse_function_call_output(p):
    out = p.get("output")
    if isinstance(out, str):
        text = out
    elif isinstance(out, dict):
        if isinstance(out.get("content"), str):
            text = out["content"]
        elif isinstance(out.get("content_items"), list):
            text = "".join(
                it.get("text", "")
                for it in out["content_items"]
                if isinstance(it, dict) and isinstance(it.get("text"), str)
            )
        else:
            text = ""
    else:
        text = ""
    # Always Kept; render_item skips when output is whitespace-only.
    if text.strip() == "":
        return ("kept", None)
    return ("kept", "TOOL RESULT: {}".format(text))


def _parse_tool_misc(p, kind):
    text = None
    for key in ("text", "input", "query", "execution", "content"):
        val = p.get(key)
        if isinstance(val, str) and val != "":
            text = val
            break
    if text is not None and text.strip() != "":
        rendered = "TOOL {}: {}".format(kind.upper(), text)
    else:
        rendered = "[tool: {}]".format(kind)
    return ("kept", rendered)


def segment_thread(lines):
    """lines: list of (line_no:int, payload:str). Mirrors backend.rs:1091-1146.
    Returns list of dicts: {start, end, prior_summary, transcript}."""
    segments = []
    buf = []
    start_line = None
    pending_prior = None
    last_no = None
    for (line_no, payload) in lines:
        last_no = line_no
        if start_line is None:
            start_line = line_no
        cls, rendered = parse_line(payload)
        if cls == "kept":
            if rendered is not None:
                buf.append(rendered)
        elif cls == "boundary":
            segments.append({
                "start": start_line,
                "end": line_no,
                "prior_summary": pending_prior,
                "transcript": "\n".join(buf),
            })
            buf = []
            start_line = None
            pending_prior = rendered  # the boundary summary
        # dropped: nothing
    if start_line is not None:
        end = last_no if last_no is not None else start_line
        segments.append({
            "start": start_line,
            "end": end,
            "prior_summary": pending_prior,
            "transcript": "\n".join(buf),
        })
    return segments


